def first_md(dp):
    fs = sorted(f for f in os.listdir(dp) if f.endswith(".md"))
    return os.path.join(dp, fs[0]) if fs else None


def main():
    mod_filter = sys.argv[1] if len(sys.argv) > 1 else None
    done = 0
    for dp, dn, fn in os.walk(FULL):
        if AI_RE.search(dp):
            continue
        mod = os.path.basename(dp)
        if mod_filter and mod != mod_filter:
            continue
        entry = ENTRIES.get(mod)
        if not entry:
            continue
        p = first_md(dp)
        if not p:
            continue
        text = open(p, encoding="utf-8").read()
        if "## 0. 零基础入门（从零开始）" in text:
            continue
        section = "\n".join(entry) + "\n"
        # 插到 frontmatter 之后
        m = re.match(r"^(---\r?\n.*?\r?\n---\r?\n)", text, re.S)
        if m:
            new = text[: m.end()] + section + text[m.end():]
        else:
            new = section + text
        open(p, "w", encoding="utf-8", newline="\n").write(new)
        done += 1
        print("inserted:", mod)
    print("total inserted:", done)


if __name__ == "__main__":
    main()
